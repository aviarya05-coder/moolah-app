-- The order entries were made in. "Recent" on screen means most recently
-- logged, not latest dated, so the screens sort by this.
alter table public.transactions add column seq bigint generated by default as identity;
create index transactions_seq on public.transactions (household_id, seq);

-- Start a budget in one go from the first-run choices (engine/setup.js): the
-- household, its owner, and its accounts, groups, categories, opening
-- balance and card hold. All or nothing, so a dropped connection never
-- leaves half a budget.
--
-- Ids come from the app (fresh uuids, so the rows can refer to each other),
-- and every row is put in the new household whatever the payload says; the
-- household-scoped foreign keys refuse any id from another household.
create function public.start_household(p jsonb) returns uuid
  language plpgsql security definer set search_path = public as $$
declare hid uuid;
begin
  if auth.uid() is null then raise exception 'Sign in first.'; end if;
  if exists (select 1 from members where user_id = auth.uid()) then raise exception 'You already have a budget.'; end if;
  if jsonb_array_length(coalesce(p->'accounts', '[]')) > 20 or jsonb_array_length(coalesce(p->'groups', '[]')) > 50
     or jsonb_array_length(coalesce(p->'categories', '[]')) > 300 or jsonb_array_length(coalesce(p->'assignments', '[]')) > 20
     or jsonb_array_length(coalesce(p->'transactions', '[]')) > 20 then
    raise exception 'That is more than a new budget starts with.';
  end if;

  insert into households (name, currency)
    values (coalesce(nullif(btrim(p->'household'->>'name'), ''), 'Our household'), coalesce(p->'household'->>'currency', 'ILS'))
    returning id into hid;
  insert into members (household_id, user_id, role, display_name)
    values (hid, auth.uid(), 'owner', nullif(btrim(p->>'displayName'), ''));

  insert into accounts (id, household_id, name, kind, sort)
    select x.id, hid, x.name, x.kind, coalesce(x.sort, 0)
      from jsonb_to_recordset(coalesce(p->'accounts', '[]')) as x(id uuid, name text, kind text, sort int);
  insert into groups (id, household_id, name, sort)
    select x.id, hid, x.name, coalesce(x.sort, 0)
      from jsonb_to_recordset(coalesce(p->'groups', '[]')) as x(id uuid, name text, sort int);
  insert into categories (id, household_id, group_id, name, sort, priority, monthly_cost)
    select x.id, hid, x."groupId", x.name, coalesce(x.sort, 0), x.priority, x."monthlyCost"
      from jsonb_to_recordset(coalesce(p->'categories', '[]'))
        as x(id uuid, "groupId" uuid, name text, sort int, priority text, "monthlyCost" numeric);
  insert into assignments (household_id, month, category_id, card_id, amount, note)
    select hid, x.month, x."categoryId", x."cardId", x.amount, x.note
      from jsonb_to_recordset(coalesce(p->'assignments', '[]'))
        as x(month date, "categoryId" uuid, "cardId" uuid, amount numeric, note text);
  insert into transactions (household_id, date, account_id, payee, category_id, pay_card_id, outflow, inflow)
    select hid, x.date, x."accountId", coalesce(x.payee, ''), x."categoryId", x."payCardId", coalesce(x.outflow, 0), coalesce(x.inflow, 0)
      from jsonb_to_recordset(coalesce(p->'transactions', '[]'))
        as x(date date, "accountId" uuid, payee text, "categoryId" uuid, "payCardId" uuid, outflow numeric, inflow numeric);
  return hid;
end $$;

revoke all on function public.start_household(jsonb) from public, anon;
grant execute on function public.start_household(jsonb) to authenticated;
